#!/bin/bash
# Assemble lib/indus/runtime.s once (dev time) into lib/indus/runtime_blob.rb.
# The compiler ships the words, not an assembler.
set -e
cd "$(dirname "$0")/.."
LLVM=/nix/store/12dd5mabslv1wsc09gdgikii91qarzca-llvm-19.1.7/bin
$LLVM/llvm-mc -triple=aarch64 -filetype=obj lib/indus/runtime.s -o /tmp/rt.o
$LLVM/llvm-objcopy -O binary --only-section=.text /tmp/rt.o /tmp/rt.bin
{
  echo "# GENERATED by tools/build_runtime.sh from lib/indus/runtime.s -- do not edit"
  echo "module Indus"
  echo "  module RuntimeBlob"
  echo "    LABELS = {"
  $LLVM/llvm-objdump -t /tmp/rt.o | awk '/ (rt_|__)/ {printf "      %s: 0x%s,\n", $NF, $1}'
  echo "    }"
  echo "    WORDS = ["
  xxd -p -c4 /tmp/rt.bin | awk '{w=$1; printf "      0x%s%s%s%s,\n", substr(w,7,2), substr(w,5,2), substr(w,3,2), substr(w,1,2)}'
  echo "    ]"
  echo "  end"
  echo "end"
} > lib/indus/runtime_blob.rb
echo "runtime: $(wc -l < lib/indus/runtime_blob.rb) lines, $(stat -f%z /tmp/rt.bin) bytes, labels: $(grep -c ': 0x' lib/indus/runtime_blob.rb)"
